import Foundation

/// Host-side build tool. Its generated Swift is compiled for the app's target.
@main
struct EmbedScriptsGenerator {
    struct InvalidInput: Error, CustomStringConvertible {
        let description: String
    }

    static func literal(_ source: String) -> String {
        var hashes = "#"
        // A raw delimiter must neither terminate nor interpolate the input.
        while source.contains("\"\"\"" + hashes) || source.contains("\\" + hashes) {
            hashes += "#"
        }
        // The added newline before the closing delimiter is consumed by
        // Swift, preserving even an input with no final newline.
        return hashes + "\"\"\"\n" + source + "\n\"\"\"" + hashes
    }

    static func main() {
        let arguments = Array(CommandLine.arguments.dropFirst())
        if arguments == ["--help"] {
            print("Usage: EmbedScriptsGenerator --output generated.swift input.js [input.js ...]")
            return
        }
        do {
            guard arguments.count >= 3, arguments[0] == "--output" else {
                throw InvalidInput(description: "Expected --output generated.swift and at least one .js input")
            }
            let output = URL(fileURLWithPath: arguments[1])
            var names = Set<String>()
            var declarations: [String] = []
            for path in arguments.dropFirst(2) {
                let url = URL(fileURLWithPath: path)
                let name = url.deletingPathExtension().lastPathComponent
                guard url.pathExtension == "js",
                      name.range(of: "^[A-Za-z_][A-Za-z0-9_]*$", options: .regularExpression) != nil else {
                    throw InvalidInput(description: "Invalid script filename: \(url.lastPathComponent)")
                }
                guard names.insert(name).inserted else {
                    throw InvalidInput(description: "Duplicate script name: \(name)")
                }
                let source = try String(contentsOf: url, encoding: .utf8)
                declarations.append("    public static let \(name): String = \(literal(source))")
            }
            let source = "// Generated by EmbedScriptsPlugin. Do not edit or commit.\n"
                + "extension EmbeddedScripts {\n"
                + declarations.joined(separator: "\n\n") + "\n}\n"
            try FileManager.default.createDirectory(
                at: output.deletingLastPathComponent(), withIntermediateDirectories: true
            )
            try source.write(to: output, atomically: true, encoding: .utf8)
        } catch {
            FileHandle.standardError.write(Data("error: Cannot embed page scripts: \(error)\n".utf8))
            exit(EXIT_FAILURE)
        }
    }
}
