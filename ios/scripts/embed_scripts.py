#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.9"
# ///
"""Generate Swift constants from UTF-8 JavaScript at Xcode build time.

No third-party dependencies: Xcode invokes its Python directly, so builds do
not need uv, network access, macros or Swift compiler plugins.
"""

import argparse
import re
from pathlib import Path


def swift_literal(source: str) -> str:
    """Choose a raw-string delimiter that cannot close or interpolate the JS."""
    hashes = "#"
    while f'"""{hashes}' in source or f"\\{hashes}" in source:
        hashes += "#"
    # The closing delimiter consumes the added newline, preserving the exact
    # source content, including whether the input ends in a newline.
    return f'{hashes}"""\n{source}\n"""{hashes}'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", required=True, type=Path, help="Generated Swift file"
    )
    parser.add_argument("scripts", nargs="+", type=Path, help="UTF-8 .js input files")
    args = parser.parse_args()

    names = set()
    declarations = []
    try:
        for path in args.scripts:
            name = path.stem
            if path.suffix != ".js" or not re.fullmatch(
                r"[A-Za-z_][A-Za-z0-9_]*", name
            ):
                raise ValueError(f"Invalid script filename: {path.name}")
            if name in names:
                raise ValueError(f"Duplicate script name: {name}")
            names.add(name)
            source = path.read_bytes().decode("utf-8")
            declarations.append(
                f"    static let {name}: String = {swift_literal(source)}"
            )

        generated = (
            "// Generated by embed_scripts.py. Do not edit or commit this file.\n"
            "enum EmbeddedScripts {\n" + "\n\n".join(declarations) + "\n}\n"
        )
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(generated, encoding="utf-8")
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(1, f"error: Cannot embed page scripts: {error}\n")


if __name__ == "__main__":
    main()
